/**
 * Video API Service
 * VidTube Platform Architecture - Phase 3 Video Upload & Management Engine
 */
import api from './api';
import axios from 'axios';

export const videoService = {
  /**
   * Request secure signature for direct client-side upload to Cloudinary
   */
  getUploadSignature: (params = {}) => {
    return api.post('/videos/upload-signature', params);
  },

  /**
   * Create video metadata record (initial status: uploading or ready)
   */
  createVideo: (videoData) => {
    return api.post('/videos', videoData);
  },

  /**
   * Confirm completed upload with technical metadata
   */
  completeUpload: (id, payload) => {
    return api.post(`/videos/${id}/complete`, payload);
  },

  /**
   * Retrieve public videos with pagination, filtering & search
   */
  getPublicVideos: (params = {}) => {
    return api.get('/videos', { params });
  },

  /**
   * Retrieve creator's uploaded videos (all visibilities and statuses)
   */
  getMyVideos: (params = {}) => {
    return api.get('/videos/my-videos', { params });
  },

  /**
   * Retrieve single video by ID (subject to visibility authorization)
   */
  getVideoById: (id) => {
    return api.get(`/videos/${id}`);
  },

  /**
   * Update video metadata (title, description, category, tags, visibility, etc.)
   */
  updateVideo: (id, videoData) => {
    return api.patch(`/videos/${id}`, videoData);
  },

  /**
   * Update video thumbnail
   */
  updateThumbnail: (id, thumbnailData) => {
    return api.patch(`/videos/${id}/thumbnail`, thumbnailData);
  },

  /**
   * Update video visibility (public, unlisted, private)
   */
  updateVisibility: (id, visibility) => {
    return api.patch(`/videos/${id}/visibility`, { visibility });
  },

  /**
   * Delete video and purge Cloudinary assets
   */
  deleteVideo: (id) => {
    return api.delete(`/videos/${id}`);
  },

  /**
   * Direct Browser Upload to Cloudinary with real progress tracking
   * @param {File} file - Video or image file
   * @param {Object} signatureData - Signature and parameters generated by backend
   * @param {Function} onProgress - Progress callback receiving percentage (0-100)
   * @param {AbortSignal} signal - Optional abort signal to cancel upload
   */
  uploadDirectToCloudinary: async (file, signatureData, onProgress, signal) => {
    const { uploadUrl, apiKey, timestamp, signature, folder } = signatureData;

    const formData = new FormData();
    formData.append('file', file);
    formData.append('api_key', apiKey);
    formData.append('timestamp', timestamp);
    formData.append('signature', signature);
    formData.append('folder', folder);

    const response = await axios.post(uploadUrl, formData, {
      signal,
      headers: {
        'Content-Type': 'multipart/form-data'
      },
      onUploadProgress: (progressEvent) => {
        if (progressEvent.total && onProgress) {
          const percentCompleted = Math.round((progressEvent.loaded * 100) / progressEvent.total);
          onProgress(percentCompleted, progressEvent.loaded, progressEvent.total);
        }
      }
    });

    return response.data;
  }
};

export default videoService;
